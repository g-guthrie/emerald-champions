#!/usr/bin/env python3
"""Generate the postgame Mega Stone archive from native form-change data."""

from __future__ import annotations

import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src" / "data" / "pokemon" / "form_change_tables.h"
OUTPUT = ROOT / "src" / "data" / "emerald_champions_mega_stones.h"


def stones() -> list[str]:
    values = re.findall(
        r"FORM_CHANGE_BATTLE_MEGA_EVOLUTION_ITEM,\s*SPECIES_[A-Z0-9_]+,\s*(ITEM_[A-Z0-9_]+)",
        SOURCE.read_text(),
    )
    return list(dict.fromkeys(values))


def main() -> None:
    values = stones()
    if len(values) < 90:
        raise SystemExit(f"expected the complete modern Mega roster, found {len(values)} stones")
    OUTPUT.write_text(
        "// Generated by scripts/generate_emerald_champions_mega_archive.py.\n"
        + "\n".join(f"    {item}," for item in values)
        + "\n"
    )
    print(f"generated postgame archive with {len(values)} Mega Stones")


if __name__ == "__main__":
    main()
